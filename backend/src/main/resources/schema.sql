CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(240) NOT NULL UNIQUE,
    category VARCHAR(120) NOT NULL,
    unit VARCHAR(64) NOT NULL
);
CREATE TABLE IF NOT EXISTS price_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    store VARCHAR(160) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK(price > 0),
    observed_on DATE NOT NULL,
    CONSTRAINT uq_price_store_day UNIQUE(product_id, store, observed_on)
);
CREATE INDEX IF NOT EXISTS ix_prices_product_date ON price_records(product_id, observed_on);
