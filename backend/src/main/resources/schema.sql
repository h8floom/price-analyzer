CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(240) NOT NULL UNIQUE,
    category VARCHAR(120) NOT NULL,
    unit VARCHAR(64) NOT NULL
);
ALTER TABLE products ADD COLUMN IF NOT EXISTS description VARCHAR(2000) NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS price_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    store VARCHAR(160) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK(price > 0),
    observed_on DATE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_prices_product_date ON price_records(product_id, observed_on);
ALTER TABLE price_records DROP CONSTRAINT IF EXISTS uq_price_store_day;

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS role VARCHAR(5) NOT NULL DEFAULT 'USER'
    CHECK (role IN ('USER', 'ADMIN'));
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS notification_mode VARCHAR(13) NOT NULL DEFAULT 'ALL'
    CHECK (notification_mode IN ('ALL', 'DECREASE_ONLY', 'OFF'));
CREATE TABLE IF NOT EXISTS favorites (
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    PRIMARY KEY(account_id, product_id)
);
CREATE INDEX IF NOT EXISTS ix_favorites_product ON favorites(product_id);
CREATE TABLE IF NOT EXISTS price_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    price_record_id BIGINT NOT NULL,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name VARCHAR(240) NOT NULL,
    store VARCHAR(160) NOT NULL,
    old_price NUMERIC(12,2) NOT NULL,
    new_price NUMERIC(12,2) NOT NULL,
    observed_on DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITH TIME ZONE,
    UNIQUE(account_id, price_record_id)
);
CREATE INDEX IF NOT EXISTS ix_notifications_inbox ON price_notifications(account_id, id);
CREATE INDEX IF NOT EXISTS ix_notifications_unread ON price_notifications(account_id, read_at);
CREATE TABLE IF NOT EXISTS password_resets (
    account_id BIGINT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) UNIQUE NOT NULL,
    issued_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS price_admin_settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    retention_days INTEGER CHECK (retention_days >= 0)
);
INSERT INTO price_admin_settings (id)
    SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM price_admin_settings WHERE id = 1);
